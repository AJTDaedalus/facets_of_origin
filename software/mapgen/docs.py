"""Render the op catalogue (and the default style's macros) from the registry."""
from __future__ import annotations

import typing

import yaml

from .recipe import PACKAGE_DIR


def _type(ann) -> str:
    s = str(ann).replace("typing.", "")
    for a, b in (("<class '", ""), ("'>", ""), ("NoneType", "None"), ("annotated_types.", ""),
                 ("pydantic.types.", "")):
        s = s.replace(a, b)
    if s.startswith("Annotated["):
        s = s[len("Annotated["):].split(",")[0]
    return s


def _default(f) -> str:
    if f.is_required():
        return "**required**"
    d = f.default
    return "—" if d is None else f"`{d!r}`".replace("'", '"')


def ops_markdown(registry) -> str:
    lines = ["# mapgen op catalogue", "",
             "<!-- GENERATED by `python -m mapgen ops --markdown`. Do not edit by hand. -->", "",
             "Coordinates and lengths are in **feet** (origin north-west, y runs south). "
             "Paint ops draw into `into` (default `canvas`). A Mask reference can be inverted as `~name`. "
             "Every step also takes `out` (the layer it makes), `id` (stable seeding) and `seed_offset`.", ""]
    group = None
    for spec in registry.list():
        if spec.group != group:
            group = spec.group
            lines += ["", f"## {group.split(' ', 1)[-1].capitalize()}", ""]
        out = spec.output.__name__ if spec.output not in (None, "same") else ("same as input" if spec.output else "paints in place")
        lines += [f"### `{spec.name}` → {out}", "", spec.doc or "", ""]
        fields = spec.params.model_fields
        if fields:
            lines += ["| param | type | default |", "|---|---|---|"]
            for name, f in fields.items():
                t = _type(f.annotation).replace("|", "\\|")
                lines.append(f"| `{name}` | {t} | {_default(f)} |")
            lines.append("")
    style = PACKAGE_DIR / "styles" / "inked_parchment.yaml"
    data = yaml.safe_load(style.read_text()) or {}
    macros = data.get("macros") or {}
    if macros:
        lines += ["", "## Macros (styles/inked_parchment.yaml)", "",
                  "Include the style (`include: [styles/inked_parchment.yaml]`) and call a macro like an op.", ""]
        for name, m in macros.items():
            params = m.get("params") or {}
            ps = ", ".join(f"`{k}`={v!r}" for k, v in params.items())
            lines += [f"### `{name}`", "", (m.get("doc") or "").strip(), "", f"Params: {ps or 'none'}", ""]
    mats = data.get("materials") or {}
    if mats:
        lines += ["", "## Materials (styles/inked_parchment.yaml)", "", "| material | type |", "|---|---|"]
        for k, v in mats.items():
            lines.append(f"| `{k}` | {v.get('type')} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
